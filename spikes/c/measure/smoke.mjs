// Smoke test: load, edit, export in Chromium.
import { serveDist, launch, openPage, sleep } from './lib.mjs'
const browserName = process.argv[2] ?? 'chromium'
const { server, origin } = await serveDist()
const browser = await launch(browserName)
const { page } = await openPage(browser, browserName)
await page.goto(process.env.URL ?? origin + '/')
await page.waitForFunction(() => window.__spike?.m.fullMs.length > 0, null, { timeout: 60000 })
console.log('pages', await page.evaluate(() => window.__spike.m.pageCount()), 'full ms', await page.evaluate(() => window.__spike.m.fullMs))
await page.click('.page[data-n="10"] .row[data-e]:not([data-e="-1"])')
await page.locator('#ed-text').press('End')
if (!process.env.NOEDIT) await page.keyboard.type(' and some more words typed here.', { delay: 60 })
await sleep(500)
console.log('updates', JSON.stringify(await page.evaluate(() => window.__spike.m.updates.slice(-3))))
console.log('inputToFrame', await page.evaluate(() => window.__spike.m.inputToFrame.slice(-5)))
await page.click('#pdf')
await page.waitForFunction(() => window.__spike.m.pdf.length > 0, null, { timeout: 120000 })
console.log('pdf', JSON.stringify(await page.evaluate(() => window.__spike.m.pdf)))
const b64 = await page.evaluate(async () => { const r = await fetch(document.getElementById('dl').href); const b = new Uint8Array(await r.arrayBuffer()); let s = ''; for (const x of b) s += String.fromCharCode(x); return btoa(s) })
const fs = await import('node:fs')
fs.writeFileSync('measure/out/browser-' + browserName + '.pdf', Buffer.from(b64, 'base64'))
console.log('status', await page.textContent('#status'))
await page.screenshot({ path: 'measure/out/smoke-' + browserName + '.png' })
await browser.close()
server.close()
